-- -----------------------------------------------------------------------------
-- 예약 슬롯 — 오늘부터 7일, 프로토타입의 6개 시간대와 잔여 수를 그대로
-- -----------------------------------------------------------------------------
insert into public.facility_slots (facility_id, slot_at, capacity, remaining)
select f.id,
       ((current_date + d) + t.hhmm) at time zone 'Asia/Seoul',
       t.capacity,
       t.remaining
from public.facilities f
cross join generate_series(0, 6) as d
cross join (values
  ('09:00'::time, 4, 2),
  ('10:30'::time, 4, 0),
  ('13:00'::time, 6, 4),
  ('14:30'::time, 4, 1),
  ('16:00'::time, 6, 3),
  ('18:30'::time, 4, 0)
) as t(hhmm, capacity, remaining)
on conflict (facility_id, slot_at) do nothing;
